"""F-44: Einstellungen überleben das Speichern und Laden eines 3MF-Projekts.

    python roundtrip_3mf.py --profiles profiles/reference_clc [--model testeck]

1. Modell mit den Profilen slicen und als 3MF exportieren
2. Prüfen, dass die CLC-Optionen in Metadata/project_settings.config stehen
3. Das 3MF ohne weitere Profile erneut slicen
4. Beide G-Codes vergleichen (wie NF-01, nur Header ausgenommen)
"""
import argparse
import glob
import os
import shutil
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import check_gcode  # noqa: E402

KEYS = ("core_layer_combine", "core_layer_height", "shell_wall_loops", "core_wall_loops", "core_shell_overlap",
        "core_avoid_extra_toolchanges", "core_toolchange_penalty")


def run(cmd, cwd):
    res = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return res.returncode


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default=os.path.join(REPO, "build", "src", "Release", "orca-slicer.exe"))
    ap.add_argument("--profiles", required=True)
    ap.add_argument("--model", default="testeck")
    a = ap.parse_args()
    prof = os.path.abspath(a.profiles)
    out = os.path.join(REPO, "build", "clc_runs", "roundtrip_3mf")
    shutil.rmtree(out, ignore_errors=True)
    first, second = os.path.join(out, "a"), os.path.join(out, "b")
    os.makedirs(first)
    os.makedirs(second)
    datadir = os.path.join(REPO, "build", "clc_test_datadir", "cli")
    fils = sorted(glob.glob(os.path.join(prof, "filament*.json")))
    rc = run([a.exe, "--datadir", datadir, "--slice", "0",
              "--load-settings", os.path.join(prof, "machine.json") + ";" + os.path.join(prof, "process.json"),
              "--load-filaments", ";".join(fils), "--export-3mf", "project.3mf", "--outputdir", first,
              os.path.join(HERE, "testmodels", a.model + ".stl")], first)
    print(f"Slicen + 3MF-Export: Exit {rc}")
    project = os.path.join(first, "project.3mf")
    settings = zipfile.ZipFile(project).read("Metadata/project_settings.config").decode("utf-8")
    missing = [k for k in KEYS if f'"{k}"' not in settings]
    print(f"Optionen im 3MF: {len(KEYS) - len(missing)}/{len(KEYS)}" + (f", fehlen: {missing}" if missing else ""))
    rc2 = run([a.exe, "--datadir", datadir, "--slice", "0", "--outputdir", second, project], second)
    print(f"Erneutes Slicen aus dem 3MF: Exit {rc2}")
    g1 = glob.glob(os.path.join(first, "*.gcode"))
    g2 = glob.glob(os.path.join(second, "*.gcode"))
    if rc or rc2 or not g1 or not g2:
        sys.exit(1)
    def split(path):
        moves, cfg, inside = [], {}, False
        for line in open(path, encoding="utf-8", errors="replace"):
            line = line.rstrip("\r\n")
            if line.startswith("; CONFIG_BLOCK_START"):
                inside = True
            elif line.startswith("; CONFIG_BLOCK_END"):
                inside = False
            elif inside and " = " in line:
                k, v = line[2:].split(" = ", 1)
                cfg[k] = v
            elif not line.startswith("; generated by"):
                moves.append(line)
        return moves, cfg
    m1, c1 = split(g1[0])
    m2, c2 = split(g2[0])
    move_diffs = sum(1 for x, y in zip(m1, m2) if x != y) + abs(len(m1) - len(m2))
    # Metadaten, die der 3MF-Import ergänzt, zählen nicht als Einstellung
    meta = {"upward_compatible_machine"}
    cfg_diffs = sorted(k for k in set(c1) | set(c2) if k not in meta and c1.get(k) != c2.get(k))
    print(f"G-Code ohne Einstellungsblock: {move_diffs} abweichende Zeilen")
    print(f"Einstellungsblock: {len(cfg_diffs)} abweichende Schlüssel {cfg_diffs[:10]}")
    sys.exit(0 if not missing and not move_diffs and not cfg_diffs else 1)


if __name__ == "__main__":
    main()
